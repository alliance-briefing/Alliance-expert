REVIEW_KINDS = ("rapport", "procedure", "contrat", "presentation")


@dataclass(frozen=True)
class Obj:
    kind: str
    phrase: str  # « le devis Stockeo »
    stem: str  # nom de fichier sans extension : « Devis_Stockeo »
    ext: str  # docx, xlsx, pptx, pdf


@dataclass(frozen=True)
class Metier:
    key: str
    title: str  # fonction du manager
    company: str
    domain: str
    boss_title: str
    peer_titles: tuple[str, ...]
    team_titles: tuple[str, ...]
    client_label: str  # Client, Famille, Usager, Partenaire…
    clients: tuple[str, ...]
    suppliers: tuple[str, ...]
    objects: tuple[Obj, ...]
    meetings: tuple[str, ...]  # sujets de réunions ponctuelles
    recurring: str  # réunion hebdomadaire de l'équipe
    incidents: tuple[str, ...]  # incidents possibles (sujet)
    folder: str  # dossier SharePoint de l'équipe
    reserved: bool = False


def _o(kind: str, phrase: str, stem: str, ext: str) -> Obj:
    return Obj(kind, phrase, stem, ext)


